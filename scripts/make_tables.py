"""Tables and numbers of the article from the result files of whole_scene_cars.py (3dseg/docs).

Run from the article folder: python scripts/make_tables.py
Inputs: docs/whole_scene_cars_abl_<run>.json (ablation runs, see the article), the label-box / own-size-box scores
(oracle runs, below) and the moving-camera evaluation (below), all measured with the 3dseg code.
"""
import json
import os

import numpy as np

DOCS = os.path.expanduser("~/Documents/MyArticles/code/3dseg/docs")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables")

# boxes scored like the models (scripts/box_scores.py on the cars of A5 / B5): labelled box / box of our own L, W, H;
# IoU raw, IoU closed, footprint IoU closed - on a grid covering box and LiDAR (see whole_scene_cars.shape_scores)
BOXES = {"A": {"label": (0.378, 0.572, 0.680), "own": (0.331, 0.532)},
         "B": {"label": (0.378, 0.546, 0.688), "own": (0.236, 0.349)}}
OURS = {"A": "A5", "B": "B5"}                     # v7: denser body triangulation
# moving camera (V2X-Seq vehicle side, 58 windows): visual odometry and detection against the labels
EGO = {"Egopath": "13\\,\\%", "Egolabels": 187, "Egofound": 25, "Egorecall": "0.13", "Egoprecision": "0.53"}


def write_macros(path, values):
    """Write LaTeX macros: one \\newcommand per item of the dict `values` (name -> value) to the file `path`."""
    with open(path, "w", encoding="utf-8") as f:
        f.write("% generated by make_tables.py - do not edit\n")
        for name, value in values.items():
            text = f"{value:.3f}" if isinstance(value, float) else str(value)
            f.write(f"\\newcommand{{\\{name}}}{{{text}}}\n")


def rows(run):
    r = json.load(open(os.path.join(DOCS, f"whole_scene_cars_abl_{run}.json")))
    return [x for x in r if "fused closed: iou" in x]


def stats(run, labels=None):
    """Means over the evaluated cars, or over the cars of `labels` only (a label tracked twice counts twice)."""
    R = [x for x in rows(run) if labels is None or x["label"] in labels]
    m = lambda k: float(np.mean([x[k] for x in R]))
    return {"n": len(R), "raw": m("fused: iou"), "closed": m("fused closed: iou"),
            "median": float(np.median([x["fused closed: iou"] for x in R])),
            "foot": m("fused closed: footprint_iou"), "herr": m("fused closed: height_err_cm"),
            "dL": float(np.mean([abs(x["length"] - x["label_length"]) for x in R])),
            "dW": float(np.mean([abs(x["width"] - x["label_width"]) for x in R])),
            "dH": float(np.mean([abs(x["height"] - x["label_height"]) for x in R])),
            "single_raw": m("single window: iou"), "single_closed": m("single closed: iou"),
            "centre": float(np.median([x["centre_err_m"] for x in R])),
            "along": float(np.median([x["pose: along-ray err m"] for x in R if "pose: along-ray err m" in x] or [np.nan])),
            "across": float(np.median([x["pose: across-ray err m"] for x in R if "pose: across-ray err m" in x] or [np.nan]))}


def main():
    os.makedirs(OUT, exist_ok=True)
    runs = {"A": ("A0", "A1", "A2", "A3", "A5", "A6"), "B": ("B0", "B1", "B2", "B3", "B5", "B6")}
    S = {run: stats(run) for site in runs for run in runs[site]}
    # the ablation on the cars evaluated in every row (the versions track slightly different cars)
    common = {site: set.intersection(*[{x["label"] for x in rows(r)} for r in runs[site]]) for site in runs}
    SC = {run: stats(run, common[site]) for site in runs for run in runs[site]}
    A, B = S[OURS["A"]], S[OURS["B"]]
    write_macros(os.path.join(OUT, "numbers.tex"), {
        "AsixClosed": A["closed"], "AsixRaw": A["raw"],
        "BsixClosed": B["closed"], "BsixRaw": B["raw"],
        "AlabClosed": BOXES["A"]["label"][1], "AlabRaw": BOXES["A"]["label"][0],
        "BlabClosed": BOXES["B"]["label"][1], "BlabRaw": BOXES["B"]["label"][0],
        "AboxClosed": BOXES["A"]["own"][1], "BboxClosed": BOXES["B"]["own"][1],
        "AsingleClosed": A["single_closed"], "BsingleClosed": B["single_closed"],
        "Acars": A["n"], "Bcars": B["n"], "AsixVClosed": S["A3"]["closed"], "BsixVClosed": S["B3"]["closed"],
        "Acentre": f"{A['centre']:.1f}", "Bcentre": f"{B['centre']:.1f}",
        "Aalong": f"{A['along']:.2f}", "Aacross": f"{A['across']:.2f}", "Balong": f"{B['along']:.1f}",
        "Bacross": f"{B['across']:.2f}", "Acommon": len(common["A"]), "Bcommon": len(common["B"]), **EGO})

    def fmt(v, d=3):
        return "--" if v is None else f"{v:.{d}f}"

    # main table: our models against boxes scored the same way
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{Cars against their accumulated LiDAR (mean over the evaluated cars). IoU against the raw and the"
             r" gap-closed reference, footprint IoU and height error against the closed one, size errors against the"
             r" labelled box. The labelled box and a box of our own estimated size are scored in the same way.}",
             r"\label{tab:main}", r"\setlength{\tabcolsep}{4pt}",
             r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{llccccccc}", r"\toprule",
             r" & & \multicolumn{2}{c}{solid IoU} & footprint & height & \multicolumn{3}{c}{size error (m)} \\",
             r"\cmidrule(lr){3-4}\cmidrule(lr){7-9}",
             r" & & raw & closed & IoU & err.\ (cm) & $L$ & $W$ & $H$ \\", r"\midrule"]
    for site, st, name in (("A", A, f"A ({A['n']} cars)"), ("B", B, f"B ({B['n']} cars)")):
        bx = BOXES[site]
        lines += [rf"\multirow{{4}}{{*}}{{{name}}} & labelled box & {bx['label'][0]:.3f} & {bx['label'][1]:.3f} & "
                  rf"{bx['label'][2]:.3f} & -- & 0 & 0 & 0 \\",
                  rf" & box of our size & {bx['own'][0]:.3f} & {bx['own'][1]:.3f} & -- & -- & {st['dL']:.2f} & "
                  rf"{st['dW']:.2f} & {st['dH']:.2f} \\",
                  rf" & best single window & {st['single_raw']:.3f} & {st['single_closed']:.3f} & -- & -- & -- & -- & -- \\",
                  rf" & \textbf{{ours}} & \textbf{{{st['raw']:.3f}}} & \textbf{{{st['closed']:.3f}}} & {st['foot']:.3f} & "
                  rf"{st['herr']:.1f} & {st['dL']:.2f} & {st['dW']:.2f} & {st['dH']:.2f} \\"]
        lines.append(r"\midrule" if site == "A" else r"\bottomrule")
    lines += [r"\end{tabular}}", r"\end{table}"]
    open(os.path.join(OUT, "main_table.tex"), "w").write("\n".join(lines) + "\n")

    # ablation: changes added one at a time
    steps = [("0", "previous (cabin within body footprint)"), ("1", "+ cabin unbounded"),
             ("2", "+ density 0.40 $\\to$ 0.25"), ("3", "+ height cap 1.9~m"),
             ("5", "+ denser body mesh (ours)"), ("6", "+ length bound 4.6~m (prior)")]
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{Ablation on both intersections, changes added one at a time. IoU and height error against the"
             rf" gap-closed LiDAR; $|\Delta L|$, $|\Delta H|$: mean size errors (m); on the cars evaluated in every"
             rf" row ({len(common['A'])} on A, {len(common['B'])} on B). The pipeline is deterministic: repeated runs"
             r" give identical numbers.}",
             r"\label{tab:ablation}", r"\setlength{\tabcolsep}{3.5pt}",
             r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{lcccccccc}", r"\toprule",
             r" & \multicolumn{4}{c}{intersection A} & \multicolumn{4}{c}{B (not used for tuning)} \\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
             r" & IoU & h.~err & $|\Delta L|$ & $|\Delta H|$ & IoU & h.~err & $|\Delta L|$ & $|\Delta H|$ \\", r"\midrule"]
    for k, name in steps:
        a, b = SC["A" + k], SC["B" + k]
        ia, ib = f"{a['closed']:.3f}", f"{b['closed']:.3f}"
        if k == "5":
            ia, ib = rf"\textbf{{{ia}}}", rf"\textbf{{{ib}}}"
        lines.append(rf"{name} & {ia} & {a['herr']:.1f} & {a['dL']:.2f} & {a['dH']:.2f} & "
                     rf"{ib} & {b['herr']:.1f} & {b['dL']:.2f} & {b['dH']:.2f} \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    open(os.path.join(OUT, "ablation.tex"), "w").write("\n".join(lines) + "\n")
    for k, v in SC.items():
        print(k, {a: round(b, 3) for a, b in v.items()})
    print("ours A", {a: round(b, 3) for a, b in A.items()}); print("ours B", {a: round(b, 3) for a, b in B.items()})


# --- the larger evaluation: DAIR-V2X-C clips and V2X-Seq-SPD sequences (dataset/*_runs/pool.py -> pooled.json) ---
RUNS = os.path.expanduser("~/Documents/MyArticles/dataset")
LARGE = [("DAIR-V2X-C", "dair_c_runs", "Dair"), ("V2X-Seq-SPD", "spd_runs", "Spd")]


def large_eval():
    """tables/large_eval.tex (per intersection and in total: our models and the labelled boxes against the raw and the
    gap-closed LiDAR, position errors) and tables/numbers_large.tex (macros) from the pooled results that exist."""
    have = [(name, json.load(open(os.path.join(RUNS, d, "pooled.json"))), json.load(open(os.path.join(RUNS, d, "chosen.json"))), m)
            for name, d, m in LARGE if os.path.exists(os.path.join(RUNS, d, "pooled.json"))]
    if not have:
        return
    lines = [r"\begin{table}[!htb]", r"\centering",
             r"\caption{Larger evaluation, no parameter changed: clips of DAIR-V2X-C and sequences of V2X-Seq-SPD,"
             r" two or three per intersection. Mean solid IoU of our models and of the labelled boxes against the"
             r" cars' raw and gap-closed accumulated LiDAR; median position error of our models along and across the"
             r" viewing ray.}",
             r"\label{tab:large}", r"\footnotesize", r"\begin{tabular}{llrcccccc}", r"\toprule",
             r"Dataset & Intersection & Cars & \multicolumn{2}{c}{raw LiDAR} & \multicolumn{2}{c}{closed LiDAR} &"
             r" \multicolumn{2}{c}{position (m)} \\",
             r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
             r" & & & ours & box & ours & box & along & across \\", r"\midrule"]
    fmt = lambda s: [str(s["cars"]), f"{s['ours raw']:.3f}", f"{s['box raw']:.3f}", f"{s['ours closed']:.3f}",
                     f"{s['box closed']:.3f}", f"{s['along m']:.2f}", f"{s['across m']:.2f}"]
    macros = {}
    for i, (name, pooled, chosen, m) in enumerate(have):
        sites = sorted(k for k in pooled if k != "all")
        for j, site in enumerate(sites):
            lines.append(" & ".join([name if j == 0 else "", site.replace("yizhuang", "yz")] + fmt(pooled[site])) + r" \\")
        lines.append(" & ".join(["", r"\textbf{all}"] + [rf"\textbf{{{v}}}" for v in fmt(pooled["all"])]) + r" \\")
        lines.append(r"\midrule" if i < len(have) - 1 else r"\bottomrule")
        a = pooled["all"]
        macros.update({f"{m}Cars": a["cars"], f"{m}Clips": len(chosen), f"{m}Sites": len(sites),
                       f"{m}Frames": sum(c["with_image"] for c in chosen),
                       f"{m}OursRaw": f"{a['ours raw']:.3f}", f"{m}BoxRaw": f"{a['box raw']:.3f}",
                       f"{m}OursClosed": f"{a['ours closed']:.3f}", f"{m}BoxClosed": f"{a['box closed']:.3f}",
                       f"{m}Along": f"{a['along m']:.2f}", f"{m}Across": f"{a['across m']:.2f}"})
    lines += [r"\end{tabular}", r"\end{table}"]
    open(os.path.join(OUT, "large_eval.tex"), "w").write("\n".join(lines) + "\n")
    write_macros(os.path.join(OUT, "numbers_large.tex"), macros)
    print("large evaluation:", {k: v for k, v in macros.items() if "Closed" in k or "Cars" in k})


if __name__ == "__main__":
    main()
    large_eval()
