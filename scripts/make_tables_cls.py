"""The end-to-end table: car models reconstructed from the classical input (masks and cuboids from the video alone,
3dseg classical_input) scored against the cars' LiDAR, on intersections A and B and on three clips of DAIR-V2X-C and
four sequences of V2X-Seq-SPD. Reads 3dseg docs/whole_scene_cars_ann_<run>_<tag>.json (improve_runs/cars_chain.sh);
writes tables_cls/e2e_table.tex and tables_cls/numbers.tex (macros \\Cls...). A label the tracker split into two
tracks keeps the longer one."""
import json
import os

import numpy as np

DOCS = os.path.expanduser("~/Documents/MyArticles/code/3dseg/docs")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables_cls")
SETS = [("A", "A", [("Acls", "e2e")]), ("B", "B", [("B", "e2e_sub2")]),
        ("D", "DAIR-V2X-C", [(n, "e2e_sub2") for n in ("c114", "c105", "c52")]),
        ("S", "V2X-Seq-SPD", [(n, "e2e_sub2") for n in ("s0054", "s0059", "s0077", "s0002")])]
KEYS = [("Ours", "fused closed: iou"), ("Lab", "box label closed: iou"), ("Own", "box own closed: iou"),
        ("Input", "box input closed: iou"), ("Single", "single closed: iou")]


def paired_ci(d, n_boot=5000, seed=0):
    """Mean of the paired differences d with its 95 % bootstrap interval: (mean, lo, hi, wins, n)."""
    d = np.asarray(d, float)
    d = d[~np.isnan(d)]
    if not len(d):
        return np.nan, np.nan, np.nan, 0, 0
    rng = np.random.default_rng(seed)
    boot = [rng.choice(d, size=len(d), replace=True).mean() for _ in range(n_boot)]
    return d.mean(), np.percentile(boot, 2.5), np.percentile(boot, 97.5), int((d > 0).sum()), len(d)


def fmt_ci(mean, lo, hi):
    return f"${mean:+.3f}$ $[{lo:+.3f}, {hi:+.3f}]$"


def cars(runs):
    out = []
    for name, tag in runs:
        best = {}
        for r in json.load(open(os.path.join(DOCS, f"whole_scene_cars_ann_{name}_{tag}.json"))):
            if "fused closed: iou" in r and (r["label"] not in best or r["windows"] > best[r["label"]]["windows"]):
                best[r["label"]] = r
        out += list(best.values())
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    macros, body = {}, []
    for s, title, runs in SETS:
        R = cars(runs)
        col = {k: np.array([r.get(key, np.nan) for r in R], float) for k, key in KEYS}
        for k in col:
            macros[f"Cls{s}{k}"] = f"{np.nanmean(col[k]):.3f}"
        macros[f"Cls{s}Cars"] = str(len(R))
        dl, di = paired_ci(col["Ours"] - col["Lab"]), paired_ci(col["Ours"] - col["Input"])
        macros[f"Cls{s}DLab"], macros[f"Cls{s}DInput"] = fmt_ci(*dl[:3]), fmt_ci(*di[:3])
        macros[f"Cls{s}WinsLab"] = str(dl[3])
        get = lambda key: np.array([r.get(key, np.nan) for r in R], float)
        macros[f"Cls{s}Lerr"] = f"{np.nanmean(np.abs(get('length') - get('label_length'))):.2f}"
        macros[f"Cls{s}Herr"] = f"{np.nanmean(get('fused closed: height_err_cm')):.0f}"
        macros[f"Cls{s}Heading"] = f"{np.nanmedian(get('heading_err_deg')):.1f}"
        macros[f"Cls{s}Along"] = f"{np.nanmedian(np.abs(get('pose: along-ray err m'))):.2f}"
        body.append(f"{title} & {len(R)} & " + " & ".join(macros[f"Cls{s}{k}"] for k, _ in KEYS)
                    + f" & {fmt_ci(*dl[:3])} & {fmt_ci(*di[:3])} \\\\")
        print(title, len(R), {k: macros[f"Cls{s}{k}"] for k, _ in KEYS}, fmt_ci(*dl[:3]), fmt_ci(*di[:3]))
    lines = [r"\begin{table}[t]", r"\centering",
             r"\caption{End to end from the video alone: car models reconstructed from the classical input "
             r"(Sect.~\ref{sec:classical}), mean solid IoU against the gap-closed LiDAR, on intersections A and B, three "
             r"clips of DAIR-V2X-C and four sequences of V2X-Seq-SPD. The labelled box, a box of "
             r"our own estimated size, the input cuboid of the classical method and the best single window are scored "
             r"in the same way; the last two columns pair our models with the labelled box and with their input "
             r"cuboid on the same cars (mean difference, 95\,\% bootstrap interval).}",
             r"\label{tab:e2e}", r"\setlength{\tabcolsep}{3pt}", r"\resizebox{\textwidth}{!}{%",
             r"\begin{tabular}{lrccccccc}", r"\toprule",
             r" & cars & ours & labelled & box of & input & single & ours $-$ labelled & ours $-$ input \\",
             r" & & & box & our size & cuboid & window & & \\", r"\midrule", *body,
             r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
    open(os.path.join(OUT, "e2e_table.tex"), "w").write("\n".join(lines) + "\n")
    with open(os.path.join(OUT, "numbers.tex"), "w") as f:
        f.write("% generated by make_tables_cls.py - do not edit\n")
        for k, v in macros.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
