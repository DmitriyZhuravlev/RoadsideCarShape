"""Copy the abstract and the body of main.tex into springer/main.tex (Springer Nature template): the generated macros
of tables_cls/numbers.tex and the tables are inlined, \\resizebox is replaced by \\footnotesize. The front matter and
the declarations of springer/main.tex are kept. Usage: python scripts/sync_springer.py (from the repository root)."""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def table(match):
    t = open(os.path.join(ROOT, match.group(1))).read().strip()
    wide = "\\resizebox" in t
    t = t.replace("\\resizebox{\\textwidth}{!}{%\n", "\\footnotesize\n").replace("\\end{tabular}}", "\\end{tabular}")
    return t.replace("tabcolsep}{3pt}", "tabcolsep}{0.8pt}") if wide else t


def main():
    m = open(os.path.join(ROOT, "main.tex")).read()
    path = os.path.join(ROOT, "springer", "main.tex")
    s = open(path).read()
    body = m[m.index("\\section{Introduction}"):m.index("\\subsubsection*{Code availability.}")]
    body = re.sub(r"\\input\{(tables[^}]*)\}", table, body)
    i, j = s.index("\\section{Introduction}"), s.index("\\backmatter")
    s = s[:i] + body + s[j:]
    i, j = s.index("% generated by make_tables"), s.index("\\newcommand{\\R}")
    s = s[:i] + open(os.path.join(ROOT, "tables_cls", "numbers.tex")).read() + "\n" + s[j:]
    abstract = m[m.index("\\begin{abstract}") + len("\\begin{abstract}"):m.index("\\keywords{")].strip()
    i = s.index("\\abstract{") + len("\\abstract{")
    j = s.index("\\keywords{", i)
    s = s[:i] + abstract + s[s.rindex("}", i, j):j] + s[j:]
    open(path, "w").write(s)


if __name__ == "__main__":
    main()
